-- Baseline schema (#31, ADR-007).
--
-- Generated once by Hibernate 6.6.15's PostgreSQL schema export from the @Entity mappings, then
-- reviewed: tables grouped by bounded context, every unique, check and foreign-key constraint given
-- an explicit name, and the export's `if exists` guards dropped. Column lists are Hibernate's own,
-- so this file diffs cleanly against a fresh export.
--
-- Constraints are named because a later migration has to name the constraint it alters, and H2 and
-- PostgreSQL auto-name unnamed ones differently: adding an enum constant means dropping and
-- re-adding its ck_ constraint. Conventions: uk_<table>_<column>, ck_<table>_<column>,
-- fk_<table>_<column>.
--
-- The same file runs on PostgreSQL and on H2 (dev, tests), so it uses only SQL both accept.
-- Never edit a migration once it has run; add V<n>__<description>.sql instead.

